"""Filing methodologies as navigation, not as moves (Generic / PARA / LYT / Zettelkasten). Pages stay where they are; each mode writes
regenerated index notes under _meta/filing/<mode>/:

- para: Projects (from active project sources), Areas (goals by area and their
  pages), Resources (captured material, notes, conversations), Archive (retired
  sources, expired pages);
- lyt: one Map of Content per community of linked pages, plus a Home map;
- zettelkasten: a numbered index of notes (stable ids by creation order) and the
  notes that still have no links.

Only files Mnemoloci generated are replaced.
"""

import time
from datetime import date
from pathlib import Path
from typing import Any

from . import graph_analysis, i18n, personal
from .core import txn
