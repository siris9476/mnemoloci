from .markdown import render_page, slugify, wikilink_targets
from .pages import alias_map, iter_pages
from .sources import load_sources
from .publish import regenerate
from .vault import load_state, require_vault, save_state

MODES = ("para", "lyt", "zettelkasten")
MARK = "mnemoloci-filing"


def _pages(vault: Path):
    return [p for p in iter_pages(vault, ("wiki",)) if not p.error and not p.merged_into and p.frontmatter.get("kind")]


def _link(p) -> str:
    return f"[[{p.slug}|{p.title}]]"


def _para(vault: Path) -> dict[str, str]:
    registry = load_sources(vault)["sources"]
    today = date.today().isoformat()
    def T(it: str, en: str) -> str:
        return i18n.t(vault, it, en)

    groups: dict[str, dict[str, list]] = {"Progetti": {}, "Aree": {}, "Risorse": {}, "Archivio": {}}
    shown = {"Progetti": T("Progetti", "Projects"), "Aree": T("Aree", "Areas"),
             "Risorse": T("Risorse", "Resources"), "Archivio": T("Archivio", "Archive")}
    pages = _pages(vault)
    by_slug = {p.slug: p for p in pages}
    for p in pages:
        names = {str(s.get("key", "")).split("/", 1)[0] for s in p.frontmatter.get("sources") or [] if isinstance(s, dict)}
        expired = str(p.frontmatter.get("validUntil") or "9999") < today
        retired = any((registry.get(n) or {}).get("retired") for n in names)
        projects = sorted(n for n in names if (registry.get(n) or {}).get("kind") == "project" and not (registry[n].get("retired")))
        if expired or (retired and not projects):
            groups["Archivio"].setdefault(T("Scadute o da fonti ritirate", "Expired or from retired sources"), []).append(p)
        elif projects:
            for n in projects:
                groups["Progetti"].setdefault(n, []).append(p)
        else:
            groups["Risorse"].setdefault(T("Materiale raccolto, note e conversazioni", "Collected material, notes and conversations"), []).append(p)
    for g in personal.goals_list(vault)["goals"]:
        linked = [by_slug[s] for s in g.get("links") or [] if s in by_slug]
        groups["Aree"].setdefault(g.get("area") or T("senza area", "no area"), []).extend(linked)
    notes = {}
    for name, sections in groups.items():
        name = shown[name]
        lines = [f"# {name}", "", T(f"> Vista PARA generata da Mnemoloci ({MARK}): le pagine restano dove sono.",
                                    f"> PARA view generated by Mnemoloci ({MARK}): the pages stay where they are."), ""]
        for section, items in sorted(sections.items()):
            unique = sorted({p.slug: p for p in items}.values(), key=lambda p: p.title.casefold())
            lines += [f"## {section}", "", *(f"- {_link(p)}" for p in unique), ""]
        if len(lines) == 4:
            lines.append(T("_Niente in questa categoria._", "_Nothing in this category._"))
        notes[f"_meta/filing/para/{name}.md"] = "\n".join(lines)
    return notes


def _lyt(vault: Path) -> dict[str, str]:
    analysis = graph_analysis.analyze(vault, top=50)
    pages = {p.slug: p for p in _pages(vault)}  # by slug: two pages may share a title
    notes, maps = {}, []
    for community in analysis["communities"]:
        name = f"MOC {community['label']}"
        maps.append(name)
        lines = [f"# {name}", "", i18n.t(vault, f"> Mappa di contenuti generata da Mnemoloci ({MARK}).",
                                           f"> Map of content generated by Mnemoloci ({MARK})."), ""]
        members = sorted((pages[s] for s in community["slugs"] if s in pages), key=lambda p: p.title.casefold())
        lines += [f"- {_link(p)}" for p in members]  # every member, not the 15-page preview
        notes[f"_meta/filing/lyt/{slugify(name)}.md"] = "\n".join(lines)
    home = ["# Home", "", i18n.t(vault, f"> Punto di partenza LYT generato da Mnemoloci ({MARK}).",
                                  f"> LYT starting point generated by Mnemoloci ({MARK})."), ""]
    home += [f"- [[{slugify(m)}|{m}]]" for m in maps] or [i18n.t(vault, "_Ancora nessun gruppo di pagine collegate._",
                                                                  "_No group of linked pages yet._")]
    alone = sorted((pages[s] for s in analysis["isolated_slugs"] if s in pages), key=lambda p: p.title.casefold())
    if alone:
        home += ["", i18n.t(vault, "## Pagine ancora senza mappa", "## Pages without a map yet"), "", *(f"- {_link(p)}" for p in alone)]
    notes["_meta/filing/lyt/home.md"] = "\n".join(home)
    return notes


ZETTEL_STATE = "zettel_ids.json"


def _zettelkasten(vault: Path, lock: VaultLock) -> dict[str, str]:
    """Numbers are handed out once and remembered (.mnemoloci/zettel_ids.json): editing a page
    never renumbers it; new pages get the next numbers, in path order."""
    pages = _pages(vault)
    state = load_state(vault, ZETTEL_STATE, "mnemoloci.zettel-ids.v1", {"ids": {}})
    ids: dict[str, int] = state["ids"]
    for p in sorted(pages, key=lambda p: p.path):
        if p.path not in ids:
            ids[p.path] = 1 + max(ids.values(), default=0)
    save_state(vault, lock, ZETTEL_STATE, state)
    pages.sort(key=lambda p: ids[p.path])
    amap = alias_map(pages)  # [[Alias]] links count too
    it = i18n.lang(vault) == "it"
    lines = ["# Indice Zettelkasten" if it else "# Zettelkasten index", "",
             (f"> Numerazione stabile per ordine di creazione, generata da Mnemoloci ({MARK})." if it
              else f"> Stable numbering in order of creation, generated by Mnemoloci ({MARK})."), ""]
    orphans = []
    inbound: dict[str, int] = {p.slug: 0 for p in pages}
    outbound: dict[str, set[str]] = {}
    for p in pages:
        outbound[p.slug] = {amap.get(t, t) for t in wikilink_targets(p.body)} - {p.slug}
        for t in outbound[p.slug]:
            if t in inbound:
                inbound[t] += 1
    for p in pages:
        out = len(outbound[p.slug])
        lines.append(f"- **{ids[p.path]:04d}** {_link(p)} · "
                     + (f"{out} link in uscita, {inbound[p.slug]} in entrata" if it
                        else f"{out} outgoing, {inbound[p.slug]} incoming links"))
        if not out and not inbound[p.slug]:
            orphans.append(p)
    if orphans:
        lines += ["", "## Note senza collegamenti" if it else "## Notes without links", "", *(f"- {_link(p)}" for p in orphans)]
    return {"_meta/filing/zettelkasten/" + ("indice.md" if it else "index.md"): "\n".join(lines)}


def generate(vault: Path, mode: str) -> dict[str, Any]:
    require_vault(vault)
    if mode not in MODES:
        raise MnemoError("BAD_MODE", f"mode must be one of {MODES}")
    writes, skipped = [], []
    with VaultLock(vault) as lock:
        notes = _zettelkasten(vault, lock) if mode == "zettelkasten" else {"para": _para, "lyt": _lyt}[mode](vault)
        for rel, body in notes.items():
            target = Path(vault) / rel
            if target.is_file() and MARK not in target.read_text("utf-8", errors="replace"):
                skipped.append(rel)
                continue
            writes += regenerate(vault, rel, {"title": Path(rel).stem, "schema": "mnemoloci.filing.v1", "mode": mode,
                                              "generated": time.strftime("%Y-%m-%dT%H:%M:%S")}, body)
        if writes:
            bundle = {"schema": txn.BUNDLE_SCHEMA, "operation_id": f"filing-{time.time_ns()}", "operation": "filing",
                      "writes": writes}
            txn.apply(vault, bundle, txn.prepare(vault, bundle).approval_sha256, lock=lock)
    return {"mode": mode, "notes": sorted(w["path"] for w in writes), "skipped_not_ours": skipped,
            "note": "navigation only: open them in Obsidian; regenerate any time"}
