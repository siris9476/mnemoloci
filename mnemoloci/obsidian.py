"""Obsidian-native views of the vault.

- canvas: a JSON Canvas map around one page (its neighbours, and theirs at depth 2),
  saved as wiki/canvases/<slug>.canvas;
- bases: .base dashboards in _meta/bases/ (pages to review, expired, people,
  saved answers, all pages by kind);
- graph colours: colour groups by page kind in .obsidian/graph.json, only when the
  user has none of their own (never overwritten).
All writes go through the transaction engine; existing files are replaced only
when Mnemoloci generated them.
"""

import json
import math
import time
from pathlib import Path
from typing import Any

from . import i18n
from .core import txn
from .core.atomic import atomic_write
from .core.errors import MnemoError
from .core.hashing import sha256_file
from .core.lock import VaultLock
from .graph_analysis import _graph
from .vault import engine, require_vault

CANVAS_DIR = "wiki/canvases"
BASES_DIR = "_meta/bases"
GENERATED = "mnemoloci-generated"
KIND_COLOR = {"concept": "5", "entity": "2", "comparison": "4", "overview": "6", "query": "3"}  # Obsidian palette 1-6
GRAPH_COLORS = [("path:wiki/concepts", 0x4F7CFF), ("path:wiki/entities", 0xE0873A), ("path:wiki/comparisons", 0x2FB37A),
                ("path:wiki/overviews", 0xB05BD6), ("path:wiki/queries", 0xD4A017), ("path:memory", 0x8A8F98)]


def _write(vault: Path, lock: VaultLock, rel: str, content: str, *, only_ours: bool) -> str:
    target = Path(vault) / rel
    entry = {"path": rel, "action": "create", "content": content}
    if target.is_file():
        if only_ours and GENERATED not in target.read_text("utf-8", errors="replace"):
            raise MnemoError("NOT_OURS", f"{rel} exists and was not generated by Mnemoloci: left untouched")
        entry = {"path": rel, "action": "replace", "content": content, "expected_sha256": sha256_file(target)}
    bundle = {"schema": txn.BUNDLE_SCHEMA, "operation_id": f"obsidian-{time.time_ns()}", "operation": "obsidian",
              "writes": [entry]}
    txn.apply(vault, bundle, txn.prepare(vault, bundle).approval_sha256, lock=lock)
    return entry["action"]


def canvas(vault: Path, center: str, *, depth: int = 1, limit: int = 40) -> dict[str, Any]:
    require_vault(vault)
    pages, adj, _ = _graph(vault)
    if center not in pages:
        raise MnemoError("NO_SUCH_PAGE", f"no wiki page {center}")
    rings = [[center]]
    seen = {center}
    for _ in range(max(1, min(depth, 2))):
        ring = sorted({n for v in rings[-1] for n in adj[v]} - seen)[: max(0, limit - len(seen))]
        if not ring:
            break
        seen |= set(ring)
        rings.append(ring)
    nodes, pos = [], {}
    for r, ring in enumerate(rings):
        # cards are 300 px wide: a crowded ring gets a larger radius so cards never overlap
        radius = 0 if r == 0 else max(520 * r, len(ring) * 340 / (2 * math.pi))
        for i, slug in enumerate(ring):
            angle = 2 * math.pi * i / max(len(ring), 1)
            x, y = round(radius * math.cos(angle)) - 150, round(radius * math.sin(angle)) - 60
            pos[slug] = (x, y)
            nodes.append({"id": slug, "type": "file", "file": pages[slug].path, "x": x, "y": y,
                          "width": 300, "height": 120 if r else 160,
                          "color": KIND_COLOR.get(pages[slug].frontmatter.get("kind"), "1")})
    edges = [{"id": f"{a}->{b}", "fromNode": a, "toNode": b}
             for a in sorted(seen) for b in sorted(adj[a] & seen) if a < b]
    doc = {"nodes": nodes, "edges": edges, "metadata": {"generator": GENERATED, "center": center,
                                                         "generated": time.strftime("%Y-%m-%d")}}
    rel = f"{CANVAS_DIR}/{center}.canvas"
    with VaultLock(vault) as lock:
        action = _write(vault, lock, rel, json.dumps(doc, ensure_ascii=False, indent=1), only_ours=True)
    return {"path": rel, "nodes": len(nodes), "edges": len(edges), "action": action}


def _base(name: str, filters: list[str], order: list[str], formulas: dict[str, str] | None = None,
          vault: Path | None = None) -> str:
    lines = [f"# {GENERATED}: {name} " + i18n.t(vault, "(rigenerato da `mnemoloci obsidian bases`)",
                                                 "(regenerated by `mnemoloci obsidian bases`)"), "filters:", "  and:"]
    lines += [f"    - '{f}'" for f in filters]
    if formulas:
        lines.append("formulas:")
        lines += [f"  {k}: '{v}'" for k, v in formulas.items()]
    lines += ["views:", "  - type: table", f'    name: "{name}"', "    order:"]
    lines += [f"      - {o}" for o in order]
    return "\n".join(lines) + "\n"


BASE_NAMES_EN = {"Pagine per tipo": "Pages by type", "Da rivedere": "To review",
                 "Scadute o da ricontrollare": "Expired or to recheck", "Persone": "People",
                 "Risposte salvate": "Saved answers"}

BASES = {
    "Pagine per tipo": (['file.inFolder("wiki")', 'kind != null', 'mergedInto == null'],
                        ["file.name", "kind", "summary", "confidence", "updated"], None),
    "Da rivedere": (['file.inFolder("wiki")', "confidence < 0.6"],
                    ["file.name", "kind", "confidence", "provenanceState", "updated"], None),
    "Scadute o da ricontrollare": (['file.inFolder("wiki")', "validUntil != null || refreshDue != null"],
                                   ["file.name", "validFrom", "validUntil", "refreshDue", "supersededBy"], None),
    "Persone": (['file.inFolder("wiki/entities")', 'entityType == "person"'],
                ["file.name", "summary", "updated", "formula.days_since"],
                {"days_since": "if(updated, ((today() - date(updated)) / 86400000).round(0), \"\")"}),
    "Risposte salvate": (['file.inFolder("wiki/queries")'], ["file.name", "question", "confidence", "updated"], None),
}


def bases(vault: Path) -> dict[str, Any]:
    require_vault(vault)
    written, skipped = [], []
    with VaultLock(vault) as lock:
        for italian, (filters, order, formulas) in BASES.items():
            name = italian if i18n.lang(vault) == "it" else BASE_NAMES_EN[italian]
            rel = f"{BASES_DIR}/{name}.base"
            try:
                written.append({"path": rel, "action": _write(vault, lock, rel, _base(name, filters, order, formulas, vault),
                                                               only_ours=True)})
            except MnemoError as exc:
                skipped.append({"path": rel, "reason": exc.message})
    return {"bases": written, "skipped": skipped,
            "note": "open them in Obsidian (Bases core plugin) or embed one in a note: ![["
                    + ("Da rivedere" if i18n.lang(vault) == "it" else "To review") + ".base]]"}


def graph_colors(vault: Path) -> dict[str, Any]:
    require_vault(vault)
    rel = ".obsidian/graph.json"
    target = Path(vault) / rel
    groups = [{"query": q, "color": {"a": 1, "rgb": rgb}} for q, rgb in GRAPH_COLORS]
    with VaultLock(vault) as lock:
        data: dict[str, Any] = {}
        if target.is_file():
            try:
                data = json.loads(target.read_text("utf-8"))
            except ValueError as exc:
                raise MnemoError("BAD_GRAPH_CONFIG", f"{rel} is not valid JSON: left untouched") from exc
            if data.get("colorGroups"):
                return {"changed": False, "note": "you already have colour groups in Obsidian: left untouched"}
        # .obsidian/ is Obsidian's own config, reserved in the transaction engine on purpose: this is
        # the one sanctioned write there, only adding colour groups, with the previous file kept aside.
        backup = None
        if target.is_file():
            backup = engine(vault) / "obsidian-backups" / f"graph-{time.strftime('%Y%m%d-%H%M%S')}.json"
            backup.parent.mkdir(parents=True, exist_ok=True)
            backup.write_bytes(target.read_bytes())
        data["colorGroups"] = groups
        target.parent.mkdir(parents=True, exist_ok=True)
        atomic_write(target, json.dumps(data, indent=2).encode("utf-8"))
    return {"changed": True, "groups": [q for q, _ in GRAPH_COLORS], "previous_saved_to": str(backup) if backup else None,
            "note": "reopen the graph view in Obsidian"}
